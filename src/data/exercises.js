// Cada ejercicio es una lista de fases que el motor genérico (useBreathEngine)
// recorre en orden y en loop. "direction" le dice al Anillo de Respiración
// cómo moverse: grow (inhala), shrink (exhala) u hold (retención/pausa).
// Como una fase siempre continúa desde el tamaño donde terminó la anterior,
// el anillo nunca necesita "devolverse" de golpe.
//
// Cada ejercicio declara además:
//   evidence  → nivel de respaldo (ver evidenceLevels)
//   reference → fuente principal contra la que se validó ritmo e indicación
//   caution   → precaución o contraindicación relevante (opcional)
// Revisión de fuentes: septiembre 2026. Si cambias un ritmo, revisa la fuente.

