/** Duración aproximada de una sesión en segundos. */
export function sessionSeconds(ex) {
  if (ex.approxSeconds) return ex.approxSeconds;
  if (ex.totalSeconds) return ex.totalSeconds;
  return ex.cycles * ex.phases.reduce((sum, p) => sum + p.duration, 0);
}

